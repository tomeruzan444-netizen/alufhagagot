/* ------------------------------------------------------------------ engine */

const used = new Map();
const norm = (s) => String(s == null ? '' : s);

const appliesTo = (rule, page) =>
  (!rule.page && !rule.pages) || rule.page === page || (rule.pages || []).includes(page);

/** Rules that delete a whole block, for the page at `page`. */
function dropRules(page) {
  return RULES.filter((r) => r.drop && appliesTo(r, page));
}

/** True if this block's text is one the audit deletes.
 *  `nth` picks which matching block to drop when several are identical
 *  (a duplicated heading: drop the first, keep the second). */
const seen = new Map();
function isDropped(text, page) {
  const t = norm(text);
  return dropRules(page).some((r) => {
    if (!t.includes(r.drop)) return false;
    const key = page + '|' + RULES.indexOf(r);
    const n = (seen.get(key) || 0) + 1;
    seen.set(key, n);
    if (r.nth && r.nth !== n) return false;
    used.set(r, (used.get(r) || 0) + 1);
    return true;
  });
}

/** Applies every text correction for `page` to a piece of visible text. */
function apply(text, page) {
  let out = norm(text);
  if (!out) return text;
  for (const rule of RULES) {
    if (rule.drop || rule.findHtml || !appliesTo(rule, page) || !out.includes(rule.find)) continue;
    out = out.split(rule.find).join(rule.to);
    used.set(rule, (used.get(rule) || 0) + 1);
  }
  return out;
}

/** Corrections that work on the markup itself, for passages split across tags
 *  (a label in <strong>, a whole <li> to remove). Runs before the HTML is
 *  parsed, so the match is exactly what the source holds. */
function applyHtml(html, page) {
  let out = norm(html);
  if (!out) return html;
  for (const rule of RULES) {
    if (!rule.findHtml || !appliesTo(rule, page) || !out.includes(rule.findHtml)) continue;
    out = out.split(rule.findHtml).join(rule.toHtml || '');
    used.set(rule, (used.get(rule) || 0) + 1);
  }
  return out;
}

/** Fails the build if a correction no longer matches anything. */
function assertAllUsed() {
  const stale = RULES.filter((r) => !used.has(r));
  if (stale.length) {
    throw new Error('text-fixes.js: ' + stale.length + ' correction(s) match nothing any more:\n  ' +
      stale.map((r) => (r.page || (r.pages || []).join(',') || 'site-wide') + ': "' + (r.find || r.drop || r.findHtml) + '"').join('\n  '));
  }
  return { rules: RULES.length, applied: [...used.values()].reduce((a, b) => a + b, 0) };
}

module.exports = { RULES, apply, applyHtml, isDropped, assertAllUsed };
